-- TreasuryOne payout batch schema (H2 2.x).
-- All money is stored in kobo (BIGINT) so there is no floating point or scale ambiguity.

-- Batch numbers: the 9-digit batch number inside every payment reference.
-- NO CYCLE + MAXVALUE means the sequence fails loudly instead of wrapping and repeating a reference.
CREATE SEQUENCE payout_batch_seq START WITH 1 INCREMENT BY 1 MAXVALUE 999999999 NO CYCLE;

-- NIP institution codes the service accepts.
CREATE TABLE supported_bank (
    bank_code  VARCHAR(6)   PRIMARY KEY,
    bank_name  VARCHAR(100) NOT NULL,
    CONSTRAINT ck_bank_code_len CHECK (CHAR_LENGTH(bank_code) = 6)
);

-- Corporate debit account. available + earmarked + debited only ever move between each other.
-- The CHECK constraints are a safety net: a balance can never go negative even if code is wrong.
CREATE TABLE corporate_account (
    account_id      VARCHAR(10) PRIMARY KEY,
    corporate_id    VARCHAR(50) NOT NULL,
    currency        VARCHAR(3)  NOT NULL DEFAULT 'NGN',
    available_kobo  BIGINT      NOT NULL,
    earmarked_kobo  BIGINT      NOT NULL DEFAULT 0,
    debited_kobo    BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT ck_acct_available CHECK (available_kobo >= 0),
    CONSTRAINT ck_acct_earmarked CHECK (earmarked_kobo >= 0),
    CONSTRAINT ck_acct_debited   CHECK (debited_kobo >= 0)
);

-- One row per accepted batch. batch_id comes from payout_batch_seq.
-- (corporate_id, batch_ref) uniqueness is what makes concurrent identical submissions create one batch.
-- content_hash is a SHA-256 of the canonical request content: it tells a resubmission (200)
-- from the same batchRef with different content (422).
-- earmarked_kobo is the OUTSTANDING earmark of this batch: the sum of its lines that are still
-- PENDING, IN_FLIGHT or UNCERTAIN. It is reduced in the same transaction as every line settlement,
-- so "earmark is exactly zero when the batch finishes" can be checked with one column.
CREATE TABLE payout_batch (
    batch_id          BIGINT       PRIMARY KEY,
    corporate_id      VARCHAR(50)  NOT NULL,
    batch_ref         VARCHAR(100) NOT NULL,
    content_hash      VARCHAR(64)  NOT NULL,
    debit_account_id  VARCHAR(10)  NOT NULL,
    currency          VARCHAR(3)   NOT NULL,
    status            VARCHAR(30)  NOT NULL,
    cancel_requested  BOOLEAN      NOT NULL DEFAULT FALSE,
    earmarked_kobo    BIGINT       NOT NULL,
    created_at        TIMESTAMP    NOT NULL,
    completed_at      TIMESTAMP,
    CONSTRAINT uq_batch_corp_ref  UNIQUE (corporate_id, batch_ref),
    CONSTRAINT fk_batch_account   FOREIGN KEY (debit_account_id) REFERENCES corporate_account (account_id),
    CONSTRAINT ck_batch_id_range  CHECK (batch_id BETWEEN 1 AND 999999999),
    CONSTRAINT ck_batch_earmark   CHECK (earmarked_kobo >= 0),
    CONSTRAINT ck_batch_status    CHECK (status IN ('ACCEPTED', 'PROCESSING', 'COMPLETED',
                                                    'COMPLETED_WITH_FAILURES', 'CANCELLED'))
);

-- One row per request line, including REJECTED ones (kept for reporting, never sent).
-- line_no is the 1-based position in the request and is the 4-digit part of the payment reference.
-- Raw request values are stored as strings so leading zeros are preserved and invalid values can be recorded.
-- amount_kobo is NULL only when the amount itself was invalid (REJECTED).
-- owner_instance is the application run that last claimed the line, which is how resume recognises
-- IN_FLIGHT lines left behind by a crashed run.
CREATE TABLE payout_line (
    line_id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id          BIGINT       NOT NULL,
    line_no           INT          NOT NULL,
    line_ref          VARCHAR(100) NOT NULL,
    account_number    VARCHAR(64)  NOT NULL,
    bank_code         VARCHAR(32)  NOT NULL,
    beneficiary_name  VARCHAR(200) NOT NULL,
    raw_amount        VARCHAR(64)  NOT NULL,
    amount_kobo       BIGINT,
    payment_ref       VARCHAR(17),
    status            VARCHAR(20)  NOT NULL,
    attempts          INT          NOT NULL DEFAULT 0,
    nip_session_id    VARCHAR(30),
    failure_code      VARCHAR(50),
    reject_reason     VARCHAR(200),
    owner_instance    VARCHAR(64),
    updated_at        TIMESTAMP    NOT NULL,
    CONSTRAINT fk_line_batch        FOREIGN KEY (batch_id) REFERENCES payout_batch (batch_id),
    CONSTRAINT uq_line_no           UNIQUE (batch_id, line_no),
    CONSTRAINT uq_line_payment_ref  UNIQUE (payment_ref),
    CONSTRAINT ck_line_no_range     CHECK (line_no BETWEEN 1 AND 5000),
    CONSTRAINT ck_line_status       CHECK (status IN ('PENDING', 'IN_FLIGHT', 'PAID', 'FAILED',
                                                      'UNCERTAIN', 'CANCELLED', 'REJECTED')),
    -- A REJECTED line has no payment reference. Every other line must have one and a positive amount.
    CONSTRAINT ck_line_shape        CHECK (
        (status = 'REJECTED' AND payment_ref IS NULL)
        OR (status <> 'REJECTED' AND payment_ref IS NOT NULL AND amount_kobo IS NOT NULL AND amount_kobo > 0))
);

CREATE INDEX ix_line_batch_status ON payout_line (batch_id, status);
